package org.pocketnutrition.core

import kotlinx.serialization.KSerializer
import kotlinx.serialization.Serializable
import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.descriptors.buildClassSerialDescriptor
import kotlinx.serialization.descriptors.element
import kotlinx.serialization.encoding.Decoder
import kotlinx.serialization.encoding.Encoder
import kotlinx.serialization.encoding.encodeStructure
import kotlinx.serialization.json.JsonDecoder
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.decodeFromJsonElement
import kotlinx.serialization.json.double
import kotlinx.serialization.json.jsonPrimitive

/**
 * One way an ingredient can be portioned, as Knowledge describes it.
 *
 * [volumeMl] is 0 for countable things and non-zero for spoons and cups. Both measures are carried
 * even where only one is read, because they arrive together from [IngredientSuggestion.servingUnits]
 * and dropping one here would mean re-fetching to get it back.
 *
 * `@Serializable` because it arrives inside a search response. Unlike the iOS twin — a separate
 * SwiftPM module holding a hard no-imports rule — this `core` package lives in the app module and
 * already has kotlinx.serialization on its classpath, so there is no invariant to protect here.
 */
@Serializable(with = ServingUnitSerializer::class)
data class ServingUnit(
    val unit: String,
    val labels: List<LocalizedText>,
    val volumeMl: Double,
    val grams: Double,
) {
    /**
     * The one unit kind that can be counted rather than measured. [buildAnchors] needs both this
     * *and* a serving mode of "item" before it will count anything.
     */
    val isItem: Boolean get() = unit == "item"
}

/**
 * Tolerant of two wire shapes, not just one. Every real API response sends the generic `labels`
 * array added in contract 2.0.0, and that is the only shape [ServingUnit] ever needs to *write* —
 * but the behavioural-corpus vector files generated by the sandbox (`build-meal-ingredient.json` and
 * friends, decoded whole via [SuggestionDecoding]) are pinned to what the sandbox itself emits, which
 * still carries the pre-2.0.0 `labelFr`/`labelEn` pair, and those files are deliberately left
 * byte-identical to that output rather than hand-edited. This is the one seam that reconciles the
 * two: decode `labels` when present, else build the same shape from `labelFr`/`labelEn`.
 */
object ServingUnitSerializer : KSerializer<ServingUnit> {
    override val descriptor: SerialDescriptor = buildClassSerialDescriptor("ServingUnit") {
        element<String>("unit")
        element<List<LocalizedText>>("labels")
        element<Double>("volumeMl")
        element<Double>("grams")
    }

    override fun serialize(encoder: Encoder, value: ServingUnit) {
        encoder.encodeStructure(descriptor) {
            encodeStringElement(descriptor, 0, value.unit)
            encodeSerializableElement(descriptor, 1, ListSerializer(LocalizedText.serializer()), value.labels)
            encodeDoubleElement(descriptor, 2, value.volumeMl)
            encodeDoubleElement(descriptor, 3, value.grams)
        }
    }

    override fun deserialize(decoder: Decoder): ServingUnit {
        val jsonDecoder = decoder as? JsonDecoder
            ?: error("ServingUnit can only be decoded from JSON")
        val obj = jsonDecoder.decodeJsonElement() as JsonObject
        val unit = obj.getValue("unit").jsonPrimitive.content
        val volumeMl = obj.getValue("volumeMl").jsonPrimitive.double
        val grams = obj.getValue("grams").jsonPrimitive.double
        val labels = obj["labels"]?.let {
            jsonDecoder.json.decodeFromJsonElement(ListSerializer(LocalizedText.serializer()), it)
        } ?: buildList {
            obj["labelFr"]?.jsonPrimitive?.contentOrNull?.let { add(LocalizedText("fr", it)) }
            obj["labelEn"]?.jsonPrimitive?.contentOrNull?.let { add(LocalizedText("en", it)) }
        }
        return ServingUnit(unit, labels, volumeMl, grams)
    }
}

/**
 * One rung of the portion ladder.
 *
 * Two shapes rather than one with nullable fields, because the two are read differently everywhere: a
 * factor step scales the base portion and carries a ready-made label, a unit step multiplies a unit
 * weight and has its label built from the count. `step-raw-weight` puts it plainly — unit steps
 * "IGNORE the base portion entirely".
 *
 * The corpus calls the second kind "unit"; it is [UnitStep] here rather than `Unit` because that name
 * is taken by kotlin.Unit and shadowing it inside a sealed hierarchy is a trap for the next reader.
 * The iOS twin, with no such collision, spells the cases `.factor` and `.unit`.
 */
sealed interface ScaleStep {
    data class FactorStep(val factor: Double, val label: String) : ScaleStep
    data class UnitStep(val unit: ServingUnit, val count: Double) : ScaleStep
}
